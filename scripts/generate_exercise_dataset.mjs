function dartString(value) {
  return `'${String(value ?? '')
    .replaceAll('\\', '\\\\')
    .replaceAll("'", "\\'")
    .replaceAll('$', '\\$')
    .replaceAll('\r', '\\r')
    .replaceAll('\n', '\\n')}'`;
}

function label(value, labels) {
  return labels[value] ?? value ?? '其他';
}

function copyIfChanged(source, target) {
  if (!existsSync(target) || statSync(source).size !== statSync(target).size) {
    copyFileSync(source, target);
  }
}

const source = JSON.parse(readFileSync(datasetFile, 'utf8'));
if (!Array.isArray(source) || source.length !== 1324) {
  throw new Error(`Expected 1324 exercises, received ${source?.length ?? 'invalid data'}`);
}

mkdirSync(assetDir, { recursive: true });
for (const exercise of source) {
  copyIfChanged(join(datasetRoot, exercise.image), join(assetDir, `${exercise.id}.jpg`));
  copyIfChanged(join(datasetRoot, exercise.gif_url), join(assetDir, `${exercise.id}.gif`));
}

const additional = source.filter((exercise) => !curatedDatasetIds.has(exercise.id));
